const LANG_NAMES = {en:"English",hi:"हिन्दी",zh:"中文",ja:"日本語",id:"Indonesia",es:"Español",fr:"Français",ar:"العربية",pt:"Português",ru:"Русский"};

function getLang(){ return localStorage.getItem("appLang") || "en"; }
function setLang(l){
  localStorage.setItem("appLang", l);
  document.documentElement.setAttribute("dir", l==="ar" ? "rtl" : "ltr");
  applyLang();
  if(typeof onLangChange==="function")onLangChange();
}
function t(key,vars){
  const dict = TRANSLATIONS[getLang()] || TRANSLATIONS.en;
  let str = dict[key] !== undefined ? dict[key] : (TRANSLATIONS.en[key] || key);
  if(vars) Object.keys(vars).forEach(k=>{ str = str.replace("{"+k+"}", vars[k]); });
  return str;
}
function applyLang(){
  const lang = getLang();
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  document.documentElement.setAttribute("dir", lang==="ar" ? "rtl" : "ltr");
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key = el.getAttribute("data-i18n");
    if(dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el=>{
    const key = el.getAttribute("data-i18n-placeholder");
    if(dict[key]) el.placeholder = dict[key];
  });
  document.querySelectorAll(".lang-switch").forEach(sel=>{
    if(sel.dataset.populated!=="1"){
      sel.innerHTML = Object.keys(LANG_NAMES).map(code=>`<option value="${code}">${LANG_NAMES[code]}</option>`).join("");
      sel.dataset.populated="1";
    }
    sel.value = lang;
  });
}
document.addEventListener("DOMContentLoaded", applyLang);
